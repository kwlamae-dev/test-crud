'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { Pool } = require('pg');
const { hashPassword } = require('./lib/password');

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL must be set to connect to Supabase Postgres');
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DATABASE_SSL_CA
    ? {
        ca: fs.readFileSync(path.resolve(process.env.DATABASE_SSL_CA), 'utf8'),
        rejectUnauthorized: true,
      }
    : { rejectUnauthorized: false },
});

if (!process.env.DATABASE_SSL_CA) {
  console.warn(
    'DATABASE_SSL_CA is not set; Supabase TLS certificate verification is disabled.',
  );
}

pool.on('error', (error) => {
  console.error('Unexpected Supabase database connection error:', error);
});

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS products (
    pid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pname TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    qty INTEGER NOT NULL DEFAULT 0 CHECK (qty >= 0)
  );

  CREATE TABLE IF NOT EXISTS users (
    uid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uname TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS orders (
    oid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid INTEGER NOT NULL REFERENCES users (uid) ON DELETE CASCADE ON UPDATE CASCADE,
    pid INTEGER NOT NULL REFERENCES products (pid) ON DELETE CASCADE ON UPDATE CASCADE,
    order_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE INDEX IF NOT EXISTS idx_orders_uid ON orders (uid);
  CREATE INDEX IF NOT EXISTS idx_orders_pid ON orders (pid);
`;

async function seedDemoData() {
  if (process.env.SEED === 'false') return;

  const { rows } = await pool.query(`
    SELECT
      (SELECT COUNT(*) FROM users) AS users,
      (SELECT COUNT(*) FROM products) AS products,
      (SELECT COUNT(*) FROM orders) AS orders
  `);
  const counts = rows[0];
  if (
    Number(counts.users) > 0 ||
    Number(counts.products) > 0 ||
    Number(counts.orders) > 0
  ) {
    return;
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const users = [];
    for (const [uname, email] of [
      ['Alice Johnson', 'alice@example.com'],
      ['Bob Smith', 'bob@example.com'],
      ['Carol Lee', 'carol@example.com'],
    ]) {
      const { rows: inserted } = await client.query(
        'INSERT INTO users (uname, email, password) VALUES ($1, $2, $3) RETURNING uid',
        [uname, email, hashPassword('password123')],
      );
      users.push(inserted[0].uid);
    }

    const products = [];
    for (const [pname, description, price, qty] of [
      ['Wireless Mouse', 'Ergonomic 2.4 GHz mouse with silent clicks.', 25.99, 42],
      ['Mechanical Keyboard', 'Hot-swappable keyboard with RGB backlight.', 79.5, 18],
      ['27" QHD Monitor', '2560 x 1440 IPS monitor with USB-C input.', 289, 7],
      ['USB-C Hub', '7-in-1 hub with HDMI, SD card reader and PD.', 45, 0],
    ]) {
      const { rows: inserted } = await client.query(
        'INSERT INTO products (pname, description, price, qty) VALUES ($1, $2, $3, $4) RETURNING pid',
        [pname, description, price, qty],
      );
      products.push(inserted[0].pid);
    }

    const daysAgo = (days) => {
      const date = new Date();
      date.setDate(date.getDate() - days);
      return date.toISOString();
    };
    for (const [userIndex, productIndex, days] of [
      [0, 0, 12],
      [2, 0, 8],
      [1, 1, 5],
      [0, 2, 3],
      [2, 3, 1],
    ]) {
      await client.query(
        'INSERT INTO orders (uid, pid, order_date) VALUES ($1, $2, $3)',
        [users[userIndex], products[productIndex], daysAgo(days)],
      );
    }
    await client.query('COMMIT');
    console.log('Seeded demo users, products and orders in Supabase.');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function initializeDatabase() {
  await pool.query(SCHEMA);
  await seedDemoData();
}

module.exports = { pool, initializeDatabase };
